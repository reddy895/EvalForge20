/**
 * Helper to convert full profile into summary card.
 */
export function toModelSummary(p: ModelProfile): ModelSummary {
  const topBenchmark = p.benchmarks[0];
  const priceStr = p.is_local
    ? 'Free (Local)'
    : p.pricing?.input_cost_per_m
    ? `$${p.pricing.input_cost_per_m.toFixed(2)}/1M in`
    : 'Cloud API';

  return {
    id: p.id,
    name: p.name,
    provider: p.provider,
    model_identifier: p.model_identifier,
    family: p.family,
    parameter_count: p.parameter_count,
    context_window: p.context_window,
    is_local: p.is_local,
    is_installed: p.is_installed,
    supports_tools: p.supports_tools,
    supports_structured_output: p.supports_structured_output,
    license: p.license,
    hardware_min_ram_gb: p.hardware.min_ram_gb,
    recommended_tasks: p.recommended_tasks,
    headline_benchmark_score: topBenchmark?.score ?? null,
    headline_benchmark_name: topBenchmark ? `${topBenchmark.benchmark_name} (${topBenchmark.metric})` : null,
    pricing_summary: priceStr,
  };
}

